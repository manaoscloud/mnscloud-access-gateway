#!/usr/bin/env bash
# Access gateway installation. Run the command generated in the App (System > Access gateways):
# it pipes the one-use authorization to src/bootstrap.ts, which claims it with the existing host
# Agent, writes /etc/mnscloud/access-gateway.env from the gateway binding and calls this script
# again with --apply.
set -Eeuo pipefail
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=scripts/lib/common.sh
source "$ROOT_DIR/scripts/lib/common.sh"
ENV_FILE="$DEFAULT_ENV_FILE"
API_BASE=""
SERVER_UUID=""
INSTALLATION_TOKEN=""
APPLY=0
while [[ $# -gt 0 ]]; do
 case "$1" in
  --api-base) API_BASE="${2:?}"; shift 2 ;;
  --server-uuid) SERVER_UUID="${2:?}"; shift 2 ;;
  --installation-token) INSTALLATION_TOKEN="${2:?}"; shift 2 ;;
  --apply) APPLY=1; shift ;;
  --help|-h) printf 'Usage: install-access-gateway.sh --api-base HTTPS_URL --server-uuid UUID [--installation-token TOKEN]\n'; exit 0 ;;
  *) die 'unsupported installation argument' ;;
 esac
done
require_root
umask 0077
VALIDATOR=/opt/mnscloud/mnscloud-agent/scripts/validate-agent.sh
[[ -f "$VALIDATOR" ]] || die 'install and enroll the MNSCloud Agent before installing the access gateway'
bash "$VALIDATOR" --require-active --require-enrolled
ensure_deno
fix_runtime_permissions
if (( APPLY == 0 )); then
 [[ -n "$API_BASE" && -n "$SERVER_UUID" ]] || die 'use the installation command generated by the App'
 # A resumed (claimed) installation needs no token; a new one reaches the bootstrap on stdin only.
 [[ -z "$INSTALLATION_TOKEN" || "$INSTALLATION_TOKEN" =~ ^[a-f0-9]{64}$ ]] || die 'use the installation command generated by the App'
 check_runtime
 printf '%s\n' "$INSTALLATION_TOKEN" | deno_run --allow-read --allow-write=/etc/mnscloud,/var/lib/mnscloud \
  --allow-net --allow-run=git,bash,ip --allow-sys=hostname,uid "$ROOT_DIR/src/bootstrap.ts" --api-base "$API_BASE" --server-uuid "$SERVER_UUID"
 exit 0
fi
[[ -f "$ENV_FILE" ]] || die 'the gateway binding has not been written; run the command generated by the App'
command -v openssl >/dev/null || DEBIAN_FRONTEND=noninteractive apt-get install -y -q openssl </dev/null
command -v nft >/dev/null || DEBIAN_FRONTEND=noninteractive apt-get install -y -q nftables </dev/null
command -v wg >/dev/null || DEBIAN_FRONTEND=noninteractive apt-get install -y -q wireguard-tools </dev/null
command -v ip >/dev/null || DEBIAN_FRONTEND=noninteractive apt-get install -y -q iproute2 </dev/null
LISTEN_ADDRESS="$(sed -n 's/^ACCESS_GATEWAY_LISTEN_ADDRESS=//p' "$ENV_FILE" | head -n 1)"
[[ "$LISTEN_ADDRESS" =~ ^[0-9a-fA-F:.]+$ ]] || die 'private environment is invalid'
install -d -m 0755 /var/lib/mnscloud /etc/mnscloud
install -d -m 0700 "$STATE_DIR" /etc/mnscloud/access-gateway "$TLS_DIR"
# Listener certificate (local, self-signed, never leaves the host except its public part, which
# the API pins for the edge). Rewritten when it is missing, expires within 30 days, or is a CA.
if listener_certificate_stale "$TLS_DIR"; then
 write_listener_certificate "$TLS_DIR" "$LISTEN_ADDRESS"
fi
bash "$ROOT_DIR/scripts/render-units.sh"
"$ROOT_DIR/scripts/update-access-gateway.sh" --env "$ENV_FILE" --no-checkout-rollback
systemctl enable "$CONTROLLER_UNIT" >/dev/null
log 'access gateway installed; the controller serves only the edge hosts and reaches only the API, OpenVault and session devices'
