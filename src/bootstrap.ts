// Installation ceremony run by the command generated in the App (existing Agent; no enrollment).
//
// 1. Reads the one-use authorization from stdin (never from arguments), claims it with the host
//    Agent identity and receives the gateway binding (key, listen address, pinned release).
// 2. Refuses to run unless the checked-out source is exactly the commit the API approved.
// 3. Writes /etc/mnscloud/access-gateway.env from the binding, installs and validates the node.
// 4. Reports verified evidence (or failure) back to the API.
// A resumed installation (Retry in the App) runs the same command without a token.

import {
  canonicalApi,
  ControlPlane,
  ControlPlaneRejected,
  loadAgentIdentity,
  privateRead,
} from './controller/control_plane.ts';
import { UUID } from './controller/contract.ts';
import { type Binding, DEFAULT_ENV, renderEnv } from './controller/env.ts';
import { parseAddress } from './shared/ip.ts';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const STATE = '/var/lib/mnscloud/access-gateway-install';
const CERT = '/etc/mnscloud/access-gateway/tls/cert.pem';

function fail(message: string): never {
  console.error(`[mnscloud-access-gateway] ERROR: ${message}`);
  Deno.exit(1);
}

function arg(name: string): string {
  const index = Deno.args.indexOf(name);
  const value = index >= 0 ? Deno.args[index + 1] : undefined;
  if (!value) fail('use the installation command generated by the App');
  return value;
}

async function run(argv: string[], capture = false): Promise<string> {
  const output = await new Deno.Command(argv[0], {
    args: argv.slice(1),
    stdout: capture ? 'piped' : 'inherit',
    stderr: 'inherit',
    stdin: 'null',
  }).output();
  if (!output.success) throw new Error(`step failed: ${argv.slice(0, 3).join(' ')}`);
  return capture ? new TextDecoder().decode(output.stdout) : '';
}

function atomicPrivate(path: string, text: string) {
  const dir = path.slice(0, path.lastIndexOf('/'));
  const info = Deno.lstatSync(dir);
  if (!info.isDirectory || info.uid !== 0 || ((info.mode ?? 0) & 0o022) !== 0) {
    throw new Error('Unsafe configuration directory');
  }
  try {
    if (Deno.lstatSync(path).isSymlink) throw new Error('Configuration symlinks are forbidden');
  } catch (error) {
    if (!(error instanceof Deno.errors.NotFound)) throw error;
  }
  const temp = `${dir}/.access-gateway-${crypto.randomUUID()}`;
  Deno.writeTextFileSync(temp, text, { mode: 0o600, createNew: true });
  Deno.chmodSync(temp, 0o600);
  Deno.renameSync(temp, path);
}

function isPrivate(address: string): boolean {
  const parsed = parseAddress(address);
  if (!parsed) return false;
  if (parsed.family === 4) {
    const [a, b] = parsed.text.split('.').map(Number);
    return a === 10 || (a === 172 && b >= 16 && b <= 31) || (a === 192 && b === 168) ||
      (a === 100 && b >= 64 && b <= 127);
  }
  return (parsed.value >> 121n) === 0x7en; // fc00::/7
}

/** Local private address used to reach the control plane (the API checks it is an Agent address). */
async function privateRouteAddress(api: string): Promise<string> {
  const host = new URL(api).hostname;
  const targets = parseAddress(host) ? [host] : [
    ...(await Deno.resolveDns(host, 'A').catch(() => [])),
    ...(await Deno.resolveDns(host, 'AAAA').catch(() => [])),
  ];
  for (const target of targets) {
    const routes = JSON.parse(await run(['ip', '-j', 'route', 'get', target], true)) as {
      prefsrc?: string;
    }[];
    const source = routes[0]?.prefsrc;
    if (source && isPrivate(source)) return source;
  }
  throw new Error('No private address of this host routes to the control plane');
}

function osRelease(): string {
  try {
    const fields = Object.fromEntries(
      Deno.readTextFileSync('/etc/os-release').split('\n').filter((l) => l.includes('=')).map(
        (l) => {
          const i = l.indexOf('=');
          return [l.slice(0, i), l.slice(i + 1).replace(/^"|"$/g, '')];
        },
      ),
    );
    const value = [fields.ID, fields.VERSION_ID].filter(Boolean).join('-');
    return /^[a-zA-Z0-9._-]{1,60}$/.test(value) ? value : Deno.build.os;
  } catch {
    return Deno.build.os;
  }
}

interface Material {
  installationUUID: string;
  state: 'installing' | 'operational' | 'failed';
  commitSha: string;
  gatewayUUID: string;
  gatewayKey: string;
  listenAddress: string;
  listenPort?: number;
}

async function readToken(): Promise<string> {
  const buffer = new Uint8Array(130);
  const read = await Deno.stdin.read(buffer);
  const token = new TextDecoder().decode(buffer.subarray(0, read ?? 0)).trim();
  if (!/^[a-f0-9]{64}$/.test(token)) {
    throw new Error('Use the installation command generated by the App');
  }
  return token;
}

async function install(apiBase: string, gateway: string) {
  const api = canonicalApi(apiBase);
  if (!UUID.test(gateway)) throw new Error('Use the installation command generated by the App');
  const client = new ControlPlane(loadAgentIdentity(api));
  let material = await client.call<Material | null>('GET', `/gateways/${gateway}/installation`);
  if (!material) {
    const token = await readToken();
    material = await client.call<Material>('POST', `/gateways/${gateway}/installation-claim`, {
      installationToken: token,
      hostname: Deno.hostname(),
      address: await privateRouteAddress(api),
    });
  }
  const operation = String(material.installationUUID);
  if (!UUID.test(operation)) throw new Error('Unsupported installation material');
  if (material.state === 'failed') {
    throw new Error(
      'The previous attempt failed; use Retry installation in the App, then rerun the resume command',
    );
  }
  const commit = (await run(['git', '-C', ROOT, 'rev-parse', 'HEAD'], true)).trim();
  if (!/^[a-f0-9]{40}$/.test(String(material.commitSha)) || commit !== material.commitSha) {
    throw new Error('Installed source differs from the approved installation release');
  }
  const listen = parseAddress(material.listenAddress);
  if (material.gatewayUUID !== gateway || !listen || !isPrivate(listen.text)) {
    throw new Error('Unsupported gateway binding');
  }
  const binding: Binding = {
    api,
    gatewayUUID: gateway,
    gatewayKey: String(material.gatewayKey),
    listenAddress: listen.text,
    listenPort: Number(material.listenPort ?? 7443),
  };
  if (!/^[a-z0-9][a-z0-9-]{1,62}$/.test(binding.gatewayKey)) {
    throw new Error('Unsupported gateway binding');
  }
  const candidate = renderEnv(binding);
  let existing: string | null = null;
  try {
    existing = privateRead(DEFAULT_ENV);
  } catch (error) {
    if (!(error instanceof Deno.errors.NotFound)) throw error;
  }
  if (existing !== null && existing !== candidate) {
    throw new Error(
      `Existing ${DEFAULT_ENV} differs from this gateway binding; remove it only if this host is not serving another access gateway`,
    );
  }
  atomicPrivate(
    `${STATE}/operation.json`,
    JSON.stringify({
      gatewayUUID: gateway,
      installationUUID: operation,
      agentUUID: client.agentUUID,
    }),
  );
  console.log('[mnscloud-access-gateway] Existing Agent validated; installing the gateway.');
  try {
    atomicPrivate(DEFAULT_ENV, candidate);
    await run(['bash', `${ROOT}/scripts/install-access-gateway.sh`, '--apply']);
    await run(['bash', `${ROOT}/scripts/validate-access-gateway.sh`]);
    const cert = privateRead(CERT);
    const der = Uint8Array.from(
      atob(cert.replace(/-----(BEGIN|END) CERTIFICATE-----|\s+/g, '')),
      (c) => c.charCodeAt(0),
    );
    const digest = new Uint8Array(await crypto.subtle.digest('SHA-256', der));
    await client.call('POST', `/installations/${operation}/report`, {
      state: 'operational',
      observed: {
        serviceActive: true,
        version: Deno.readTextFileSync(`${ROOT}/VERSION`).trim(),
        hostname: Deno.hostname(),
        operatingSystem: osRelease(),
        architecture: Deno.build.arch,
        listenAddress: binding.listenAddress,
        listenPort: binding.listenPort,
        listenerCertificateSha256: Array.from(digest, (b) => b.toString(16).padStart(2, '0')).join(
          '',
        ),
        listenerCertificatePem: cert,
      },
    });
  } catch (error) {
    await client.call('POST', `/installations/${operation}/report`, { state: 'failed' }).catch(
      () => {},
    );
    throw error;
  }
  console.log('[mnscloud-access-gateway] Installation verified and registered in the App.');
}

if (import.meta.main) {
  if (Deno.uid() !== 0) fail('Root privileges are required');
  Deno.mkdirSync(STATE, { recursive: true, mode: 0o700 });
  const info = Deno.lstatSync(STATE);
  if (info.isSymlink || info.uid !== 0 || ((info.mode ?? 0) & 0o077) !== 0) {
    fail('Unsafe installation state directory');
  }
  const lock = Deno.openSync(`${STATE}/.lock`, { create: true, write: true, mode: 0o600 });
  try {
    lock.lockSync(true);
    await install(arg('--api-base'), arg('--server-uuid'));
  } catch (error) {
    const message = error instanceof ControlPlaneRejected ||
        (error instanceof Error && !/step failed/.test(error.message))
      ? (error as Error).message
      : 'An installation step failed (see the message above). Fix it, use Retry installation in the App, then rerun the resume command.';
    fail(message);
  } finally {
    lock.close();
  }
}
